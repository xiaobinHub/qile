const assert = require("node:assert/strict")
const fs = require("node:fs")
const ts = require("typescript")
require.extensions[".ts"] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
}).outputText, file)
const { occurrences } = require("../../frontend/parent/src/domain/calendar.ts")
const { emptyCalendarDraft, addDraftTask, placeDraftTask, editDraftTask, draftOccurrences, calendarDraftOperations, calendarDraftSummary, deletedDraftTasks, restoreDraftTask } = require("../../frontend/parent/src/domain/calendar-draft.ts")
const preset = { id: "reading", title: "阅读", categoryId: "study", startTime: "18:00", endTime: "18:30", points: 5 }
const data = { schemaVersion: 2, settings: {}, categories: [], taskPresets: [preset], series: [{ ...preset, id: "series", note: "保留备注", startDate: "2026-10-28", recurrence: { freq: "daily", interval: 1, endType: "count", count: 5 } }], exceptions: [], completions: [], ledger: [], gifts: [], operationLog: [] }
const original = structuredClone(data)
const task = occurrences(data, "2026-10-28", "2026-10-28")[0]
let draft = addDraftTask(emptyCalendarDraft(), preset, "2026-10-30", "draft:1")
assert.equal(draftOccurrences(data, "2026-10-30", "2026-10-30", draft).length, 2)
const added = draft.added[0]
draft = placeDraftTask(draft, added, "2026-11-05")
assert.equal(calendarDraftSummary(draft).added, 1)
assert.equal(calendarDraftSummary(draft).moved, 0)
assert.equal(calendarDraftOperations(draft)[0].payload.task.startDate, "2026-11-05")
assert.equal(calendarDraftOperations(draft)[0].payload.task.recurrence, null)
draft = placeDraftTask(draft, draft.added[0], null)
assert.deepEqual(calendarDraftOperations(draft), [])
draft = placeDraftTask(draft, task, "2026-10-29")
assert.equal(draftOccurrences(data, "2026-10-28", "2026-10-28", draft).length, 0)
assert.equal(draftOccurrences(data, "2026-10-29", "2026-10-29", draft).length, 2)
let projected = draftOccurrences(data, "2026-10-29", "2026-10-29", draft).find(item => item.occurrenceKey === task.occurrenceKey)
assert.equal(projected.originalDate, "2026-10-28")
draft = placeDraftTask(draft, projected, "2026-11-06")
assert.equal(draftOccurrences(data, "2026-11-06", "2026-11-06", draft)[0].occurrenceKey, task.occurrenceKey)
let operation = calendarDraftOperations(draft)[0]
assert.equal(operation.payload.occurrenceKey, "series@2026-10-28")
assert.equal(operation.payload.task.note, "保留备注")
assert.equal(operation.payload.task.recurrence, null)
assert.equal(operation.payload.scope, "only")
projected = draftOccurrences(data, "2026-11-06", "2026-11-06", draft)[0]
draft = placeDraftTask(draft, projected, "2026-10-28")
assert.deepEqual(calendarDraftOperations(draft), [])
draft = placeDraftTask(placeDraftTask(draft, task, "2026-11-06"), task, null)
assert.equal(calendarDraftSummary(draft).deleted, 1)
assert.equal(calendarDraftOperations(draft).length, 1)
assert.deepEqual(calendarDraftOperations(draft)[0], { kind: "task.delete", payload: { occurrenceKey: task.occurrenceKey, scope: "only" } })
assert.equal(draftOccurrences(data, "2026-10-29", "2026-11-01", draft).length, 4)
assert.deepEqual(data, original, "Draft edits never mutate real business data")
const originalTask = {title:task.title,note:task.note,startDate:task.date,startTime:task.startTime,endTime:task.endTime,categoryId:task.categoryId,points:task.points,recurrence:null}
draft = editDraftTask(emptyCalendarDraft(), task, {...originalTask,title:'修改阅读',points:20})
projected = draftOccurrences(data,task.date,task.date,draft)[0]
assert.equal(projected.title,'修改阅读')
draft = placeDraftTask(draft,projected,'2026-11-06')
operation = calendarDraftOperations(draft)[0]
assert.equal(operation.payload.task.title,'修改阅读')
assert.equal(operation.payload.task.points,20)
assert.equal(operation.payload.task.startDate,'2026-11-06')
assert.equal(operation.payload.scope,'only')
draft = placeDraftTask(draft,projected,task.date)
assert.equal(calendarDraftOperations(draft)[0].payload.task.title,'修改阅读','Moving back preserves field edits')
draft = editDraftTask(draft,projected,originalTask)
assert.deepEqual(calendarDraftOperations(draft),[],'Restoring all fields removes the draft change')
draft = editDraftTask(emptyCalendarDraft(),task,{...originalTask,startDate:'2026-11-06'})
draft = placeDraftTask(draft,draftOccurrences(data,'2026-11-06','2026-11-06',draft)[0],task.date)
assert.deepEqual(calendarDraftOperations(draft),[],'Moving back after a date-only edit is a no-op')
draft = addDraftTask(emptyCalendarDraft(),preset,task.date,'draft:edit')
draft = editDraftTask(draft,draft.added[0],{...originalTask,title:'新增后编辑'})
assert.equal(calendarDraftOperations(draft)[0].kind,'task.create')
assert.equal(calendarDraftOperations(draft)[0].payload.task.title,'新增后编辑')
draft = editDraftTask(emptyCalendarDraft(),task,{...originalTask,title:'编辑后删除'})
draft = placeDraftTask(draft,task,null)
assert.equal(calendarDraftOperations(draft)[0].kind,'task.delete')
assert.deepEqual(data,original)
draft = placeDraftTask(emptyCalendarDraft(),task,null)
assert.equal(deletedDraftTasks(draft).length,1)
draft = restoreDraftTask(draft,task.occurrenceKey)
assert.deepEqual(calendarDraftOperations(draft),[],'Undo a plain deletion removes the pending operation')
draft = editDraftTask(draft,task,{...originalTask,title:'撤销后保留编辑',points:15})
draft = placeDraftTask(draft,task,'2026-11-03')
const beforeDelete = calendarDraftOperations(draft)
draft = placeDraftTask(draft,task,null)
assert.equal(deletedDraftTasks(draft)[0].title,'撤销后保留编辑')
assert.equal(deletedDraftTasks(draft)[0].date,'2026-11-03')
draft = restoreDraftTask(draft,task.occurrenceKey)
assert.deepEqual(calendarDraftOperations(draft),beforeDelete,'Undo restores the edited fields and moved date exactly')
assert.equal(deletedDraftTasks(draft).length,0)
assert.equal(calendarDraftSummary(draft).moved,1)
assert.deepEqual(restoreDraftTask(draft,task.occurrenceKey),draft,'Undo is idempotent')
const other = occurrences(data,'2026-10-29','2026-10-29')[0]
draft = placeDraftTask(placeDraftTask(draft,task,null),other,null)
draft = restoreDraftTask(draft,task.occurrenceKey)
assert.equal(deletedDraftTasks(draft).length,1,'Undo affects only the selected deletion')
assert.equal(deletedDraftTasks(draft)[0].occurrenceKey,other.occurrenceKey)
draft = addDraftTask(emptyCalendarDraft(),preset,task.date,'draft:removed')
draft = placeDraftTask(draft,draft.added[0],null)
assert.equal(deletedDraftTasks(draft).length,0,'Removed new drafts have no pending server deletion')
assert.deepEqual(data,original)
console.log(JSON.stringify({ passed: true, checks: ["preset copy", "new-task move/delete", "only final date saved", "move back cancels change", "moved task delete", "cross-month projection", "original recurrence key and notes", "draft leaves source unchanged"] }))
