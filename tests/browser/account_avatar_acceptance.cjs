const assert=require('node:assert/strict')
const path=require('node:path')
async function exerciseAccountAvatar({dad,api,axe,stage,out}) {
 stage('account avatar: default, four labeled choices, cancel, failure retry and persistent personal selection')
 assert.equal((await api(dad,'/api/auth/me')).user.avatarId,'father')
 await dad.locator('#changeAccountAvatar img').waitFor()
 await dad.locator('#changeAccountAvatar').click()
 const dialog=dad.locator('#accountAvatarDialog')
 assert.deepEqual(await dialog.locator('.account-avatar-choice-name').allTextContents(),['爸爸','妈妈','爷爷','奶奶'])
 assert.equal(await dialog.getByRole('radio',{name:'爸爸',exact:true}).isChecked(),true)
 await dialog.getByRole('radio',{name:'妈妈',exact:true}).check()
 await dialog.getByRole('button',{name:'取消',exact:true}).click()
 await dialog.waitFor({state:'hidden'})
 assert.equal((await api(dad,'/api/auth/me')).user.avatarId,'father')
 await dad.waitForFunction(()=>document.activeElement?.id==='changeAccountAvatar')
 for (const [width,height] of [[1305,890],[820,1180],[390,844]]) {
  await dad.setViewportSize({width,height})
  await dad.locator('#changeAccountAvatar').click()
  await dad.waitForFunction(()=>Array.from(document.querySelectorAll('#accountAvatarDialog img')).every(i=>i.complete&&i.naturalWidth===500&&i.naturalHeight===500))
  const box=await dialog.boundingBox();assert.ok(box.x>=0&&box.y>=0&&box.x+box.width<=width+1&&box.y+box.height<=height+1)
  await axe(dad,'account-avatar-'+width)
  await dad.screenshot({path:path.join(out,'account-avatar-'+width+'.png')})
  await dad.keyboard.press('Escape');await dialog.waitFor({state:'hidden'})
 }
 await dad.setViewportSize({width:1200,height:900})
 await dad.locator('#changeAccountAvatar').click()
 await dialog.getByRole('radio',{name:'奶奶',exact:true}).check()
 await dad.route('**/api/account/profile',route=>route.fulfill({status:503,json:{error:'头像暂时无法保存'}}),{times:1})
 await dialog.locator('#saveAccountAvatar').click()
 await dialog.getByText('头像暂时无法保存',{exact:true}).waitFor()
 assert.equal(await dialog.getByRole('radio',{name:'奶奶',exact:true}).isChecked(),true)
 assert.equal((await api(dad,'/api/auth/me')).user.avatarId,'father')
 await dialog.locator('#saveAccountAvatar').click();await dialog.waitFor({state:'hidden'})
 assert.equal((await api(dad,'/api/auth/me')).user.avatarId,'grandmother')
 assert.equal((await api(dad,'/api/auth/me')).user.familyRole,'grandmother')
 assert.equal(await dad.locator('[data-account-family-role]').innerText(),'奶奶')
 assert.match(await dad.locator('#changeAccountAvatar img').getAttribute('src'),/grandmother.png/)
 await dad.reload();await dad.locator('[data-view="settings"]').click();await dad.locator('#openAccountManagement').click()
 assert.equal(await dad.locator('[data-account-family-role]').innerText(),'奶奶')
 await dad.locator('#changeAccountAvatar').click()
 assert.equal(await dialog.getByRole('radio',{name:'奶奶',exact:true}).isChecked(),true)
 await dialog.getByRole('radio',{name:'爸爸',exact:true}).check()
 await dialog.locator('#saveAccountAvatar').click();await dialog.waitFor({state:'hidden'})
 assert.equal((await api(dad,'/api/auth/me')).user.avatarId,'father')
}
module.exports={exerciseAccountAvatar}
