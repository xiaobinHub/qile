const assert=require('node:assert/strict')
const path=require('node:path')
async function exerciseFamilyRole({admin,api,axe,stage,out,password}) {
 await admin.locator('.admin-account-avatar img').first().waitFor()
 stage('admin family role: placeholder never blocks submission, catalog retry, cancel and persistence')
 await admin.route('**/api/admin/account-avatars',route=>route.fulfill({status:503,json:{error:'角色图片暂时无法加载'}}),{times:1})
 await admin.locator('#openCreateUser').click()
 let dialog=admin.getByRole('dialog')
 await dialog.getByText('角色图片暂时无法加载',{exact:true}).waitFor()
 assert.equal(await admin.locator('button[form="createUser"]').isDisabled(),false)
 assert.equal(await dialog.locator('[data-avatar-placeholder]').count(),4)
 await dialog.getByRole('radio',{name:'妈妈',exact:true}).check()
 await axe(admin,'admin-role-placeholder')
 await admin.screenshot({path:path.join(out,'admin-role-placeholder.png')})
 await admin.locator('#createLogin').fill('qarolefallback');await admin.locator('#createNickname').fill('占位图提交')
 await admin.locator('#createPassword').fill(password)
 await admin.locator('button[form="createUser"]').click();await dialog.waitFor({state:'hidden'})
 const fallback=(await api(admin,'/api/admin/users')).users.find(u=>u.loginName==='qarolefallback')
 assert.equal(fallback.familyRole,'mother');assert.equal(fallback.avatarId,'mother')
 await admin.route('**/api/admin/account-avatars',route=>route.fulfill({status:503,json:{error:'角色图片暂时无法加载'}}),{times:1})
 await admin.locator('#openCreateUser').click();await dialog.getByText('角色图片暂时无法加载',{exact:true}).waitFor()
 await dialog.getByRole('radio',{name:'奶奶',exact:true}).check()
 await dialog.getByRole('button',{name:'重新加载',exact:true}).click()
 await admin.waitForFunction(()=>!document.querySelector('#createFamilyRoleError')?.textContent)
 await dialog.locator('img:not([data-avatar-placeholder])').first().waitFor()
 assert.deepEqual(await dialog.getByRole('radio').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('aria-label'))),['爸爸','妈妈','爷爷','奶奶'])
 assert.equal(await dialog.getByRole('radio',{name:'奶奶',exact:true}).isChecked(),true)
 await admin.locator('#cancelCreate').click();await dialog.waitFor({state:'hidden'})
 assert.equal((await api(admin,'/api/admin/users')).users.some(u=>u.loginName==='qarole'),false)
 // Successful catalog with unreadable image URLs also keeps role selection and submission available.
 await admin.route('**/qa-broken-avatar/*',route=>route.fulfill({status:404,body:''}))
 const roles=[['father','爸爸'],['mother','妈妈'],['grandfather','爷爷'],['grandmother','奶奶']]
 await admin.route('**/api/admin/account-avatars',route=>route.fulfill({json:{expiresIn:3600,avatars:roles.map(([id,label])=>({id,label,url:new URL(admin.url()).origin+'/qa-broken-avatar/'+id}))}}),{times:1})
 const brokenImages=Promise.all(roles.map(([id])=>admin.waitForResponse(response=>response.url().endsWith('/qa-broken-avatar/'+id))))
 await admin.locator('#openCreateUser').click()
 await brokenImages
 await admin.waitForFunction(()=>document.querySelectorAll('#createUser [data-avatar-placeholder]').length===4)
 await dialog.getByRole('radio',{name:'爷爷',exact:true}).check()
 await admin.locator('#createLogin').fill('qaroleimage');await admin.locator('#createNickname').fill('图片失败提交')
 await admin.locator('#createPassword').fill(password)
 await admin.locator('button[form="createUser"]').click();await dialog.waitFor({state:'hidden'})
 const imageFallback=(await api(admin,'/api/admin/users')).users.find(u=>u.loginName==='qaroleimage')
 assert.equal(imageFallback.familyRole,'grandfather');assert.equal(imageFallback.avatarId,'grandfather')
 await admin.unroute('**/qa-broken-avatar/*')
 for(const [width,height] of [[1273,890],[820,1180],[390,844]]) {
  await admin.setViewportSize({width,height})
  await admin.locator('#openCreateUser').click()
  await dialog.getByRole('radio',{name:'爸爸',exact:true}).waitFor()
  await admin.waitForFunction(()=>Array.from(document.querySelectorAll('.family-role-image img')).every(i=>i.complete&&i.naturalWidth===500))
  const box=await dialog.boundingBox();assert.ok(box.x>=0&&box.y>=0&&box.x+box.width<=width+1&&box.y+box.height<=height+1)
  assert.equal(await admin.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
  await axe(admin,'admin-family-role-'+width)
  await admin.screenshot({path:path.join(out,'admin-family-role-'+width+'.png')})
  await admin.locator('#cancelCreate').click();await dialog.waitFor({state:'hidden'})
 }
 await admin.setViewportSize({width:1200,height:900})
 await admin.locator('#openCreateUser').click()
 await admin.locator('#createLogin').fill('qarole');await admin.locator('#createNickname').fill('角色测试')
 await dialog.getByRole('radio',{name:'奶奶',exact:true}).check();await admin.locator('#createPassword').fill(password)
 await admin.route('**/api/admin/users',route=>route.request().method()==='POST'?route.fulfill({status:503,json:{error:'开通暂时失败'}}):route.continue(),{times:1})
 await admin.locator('button[form="createUser"]').click()
 await dialog.getByText('开通暂时失败',{exact:true}).waitFor()
 assert.equal(await dialog.getByRole('radio',{name:'奶奶',exact:true}).isChecked(),true)
 await admin.locator('button[form="createUser"]').click();await dialog.waitFor({state:'hidden'})
 const user=(await api(admin,'/api/admin/users')).users.find(u=>u.loginName==='qarole')
 assert.equal(user.familyRole,'grandmother');assert.equal(user.avatarId,'grandmother');assert.equal(user.role,'parent')
 await admin.reload();await admin.locator('#openCreateUser').waitFor()
 assert.equal((await api(admin,'/api/admin/users')).users.find(u=>u.id===user.id).familyRole,'grandmother')
 assert.equal(await admin.getByRole('columnheader',{name:'角色',exact:true}).count(),0)
 const row=admin.locator(`[data-user-id="${user.id}"]`)
 assert.equal(await row.locator('td').first().locator('[data-family-role]').innerText(),'奶奶')
 await row.locator('.admin-account-avatar img').waitFor()
 assert.match(await row.locator('.admin-account-avatar img').getAttribute('src'),/grandmother.png/)
 const bootstrap=(await api(admin,'/api/admin/users')).users.find(u=>u.role==='admin')
 assert.equal(await admin.locator(`[data-user-id="${bootstrap.id}"] [data-family-role]`).innerText(),'爸爸')
 for(const [width,height] of [[1273,890],[820,1180],[390,844]]) {
  await admin.setViewportSize({width,height})
  assert.equal(await admin.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
  await axe(admin,'admin-avatar-role-list-'+width)
  await admin.screenshot({path:path.join(out,'admin-avatar-role-list-'+width+'.png')})
 }
 await admin.setViewportSize({width:1200,height:900})
 await admin.locator('#openCreateUser').click()
 assert.equal(await admin.locator('#createFamilyRoleHelp').count(),0)
 await admin.locator('#cancelCreate').click();await admin.getByRole('dialog').waitFor({state:'hidden'})
}
module.exports={exerciseFamilyRole}
