const assert = require('node:assert/strict')
const path = require('node:path')
const { selectTime } = require('./picker_actions.cjs')

async function exercisePresetDuration({dad,firstId,out,api,axe,stage}) {
  stage('preset duration: same-row fields, midnight validation, persistence and edit round trip')
  for(const [width,height] of [[1305,890],[820,1180],[390,844]]) {
    await dad.setViewportSize({width,height})
    await dad.locator('[data-view="settings"]').click()
    await dad.locator('#openTaskPresetsSettings').click()
    await dad.locator('#settingsAddPreset').click()
    const dialog=dad.locator('#taskPresetEditorDialog')
    assert.equal(await dad.locator('#presetEnd').count(),0)
    const category=await dad.locator('#presetCategory').boundingBox(), points=await dad.locator('#presetPoints').boundingBox()
    assert.ok(Math.abs(category.y-points.y)<2,'Category and reward share a row')
    await dad.locator('#presetTitle').fill('时长配置'+width)
    await dad.locator('#presetPoints').fill('13')
    await selectTime(dad,'presetDuration',1,10)
    await selectTime(dad,'presetStart',18,15)
    assert.equal(await dad.locator('#presetDuration').inputValue(),'1小时10分钟')
    await axe(dad,`preset-duration-${width}`)
    await dad.screenshot({path:path.join(out,`preset-duration-${width}.png`)})
    await dialog.getByRole('button',{name:'保存配置',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    let record=await api(dad,`/api/children/${firstId}/data`)
    const preset=record.data.taskPresets.find(p=>p.title==='时长配置'+width)
    assert.equal(preset.startTime,'18:15'); assert.equal(preset.endTime,'19:25'); assert.equal(preset.points,13)
    await dad.locator(`[data-preset-edit="${preset.id}"]`).click()
    assert.equal(await dad.locator('#presetDuration').inputValue(),'1小时10分钟')
    await selectTime(dad,'presetStart',23,30)
    assert.equal(await dad.locator('#presetDuration').inputValue(),'0小时29分钟')
    await selectTime(dad,'presetDuration',0,0)
    await dialog.getByRole('button',{name:'保存配置',exact:true}).click()
    await dialog.getByText('持续时长必须大于0分钟。',{exact:true}).first().waitFor()
    await selectTime(dad,'presetDuration',0,20)
    await dialog.getByRole('button',{name:'保存配置',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    record=await api(dad,`/api/children/${firstId}/data`)
    assert.equal(record.data.taskPresets.find(p=>p.id===preset.id).endTime,'23:50')
    await dad.locator(`[data-preset-menu="${preset.id}"]`).click()
    await dad.locator(`[data-preset-delete="${preset.id}"]`).click()
    await dad.getByRole('alertdialog').getByRole('button',{name:'确认',exact:true}).click()
    await dad.getByRole('alertdialog').waitFor({state:'hidden'})
    await dad.locator(`[data-preset-edit="${preset.id}"]`).waitFor({state:'hidden'})
  }
  await dad.setViewportSize({width:1135,height:789})
}
module.exports={exercisePresetDuration}
