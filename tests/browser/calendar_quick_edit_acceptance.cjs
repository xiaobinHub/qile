async function showDate(page, date) {
  await page.locator(`[data-cell-day="${date}"]`).evaluate((cell) => {
    const calendar = cell.closest(".month-scroll")
    calendar.scrollTop += cell.getBoundingClientRect().top - calendar.getBoundingClientRect().top - calendar.querySelector(".weekday-row").clientHeight - 4
  })
}
async function point(locator) {
  const bounds = await locator.boundingBox()
  assert.ok(bounds, "Drag target is rendered")
  return { x: bounds.x + bounds.width / 2, y: bounds.y + Math.min(bounds.height / 2, 70) }
}
async function drag(page, source, target, onHover) {
  const start = await point(source), end = await point(target)
  await page.mouse.move(start.x, start.y)
  await page.mouse.down()
  await page.mouse.move(end.x, end.y, { steps: 12 })
  if (onHover) await onHover()
  await page.mouse.up()
}
async function touchDrag(page, source, target, corner = false) {
  const bounds = corner ? await source.boundingBox() : null
  const start = bounds ? {x:bounds.x+bounds.width-8,y:bounds.y+bounds.height-8} : await point(source), end = await point(target)
  const cdp = await page.context().newCDPSession(page)
  const send = (type, x, y) => cdp.send("Input.dispatchTouchEvent", { type, touchPoints: type === "touchEnd" ? [] : [{ x, y, id: 1 }] })
  await send("touchStart", start.x, start.y)
  await page.waitForTimeout(260)
  // Drag directly toward the date, including diagonals dominated by horizontal movement.
  for (let step = 1; step <= 12; step++) await send("touchMove", start.x + (end.x - start.x) * step / 12, start.y + (end.y - start.y) * step / 12)
  await send("touchEnd", end.x, end.y)
  await cdp.detach()
}
async function checkDragScroll(page, source) {
  const calendar = page.locator('#monthCalendar')
  const bounds = await calendar.boundingBox()
  const headerHeight = await calendar.locator('.weekday-row').evaluate(el => el.clientHeight)
  for (const [edge, y] of [['bottom', bounds.y + bounds.height - 8], ['top', bounds.y + headerHeight + 8]]) {
    const before = await calendar.evaluate(el => el.scrollTop)
    const start = await point(source)
    await page.mouse.move(start.x, start.y)
    await page.mouse.down()
    try {
      await page.mouse.move(bounds.x + bounds.width * 0.65, y, {steps: 12})
      await page.locator('.quick-edit-drag-ghost').waitFor()
      await page.waitForTimeout(750)
      assert.equal(await calendar.evaluate(el => el.scrollTop), before, `Dragging near the ${edge} edge must not scroll the calendar`)
      if (edge === 'top') {
        await page.mouse.wheel(0, 160)
        await page.waitForFunction(top => document.querySelector('#monthCalendar').scrollTop > top + 30, before)
      }
    } finally {
      await page.mouse.move(bounds.x + bounds.width / 2, 0)
      await page.mouse.up()
    }
  }
}
async function swipeCalendar(page) {
  const calendar = page.locator('#monthCalendar')
  const bounds = await calendar.boundingBox()
  const headerHeight = await calendar.locator('.weekday-row').evaluate(el => el.clientHeight)
  const before = await calendar.evaluate(el => el.scrollTop)
  const x = bounds.x + bounds.width - 6
  const startY = bounds.y + headerHeight + (bounds.height - headerHeight) * 0.7
  const cdp = await page.context().newCDPSession(page)
  try {
    await cdp.send('Input.dispatchTouchEvent', {type:'touchStart',touchPoints:[{x,y:startY,id:1}]})
    for (let step = 1; step <= 10; step++) {
      await cdp.send('Input.dispatchTouchEvent', {type:'touchMove',touchPoints:[{x,y:startY-step*12,id:1}]})
      await page.waitForTimeout(20)
    }
    await page.waitForTimeout(150)
    await cdp.send('Input.dispatchTouchEvent', {type:'touchEnd',touchPoints:[]})
    await page.waitForFunction(top => document.querySelector('#monthCalendar').scrollTop > top + 30, before)
    assert.equal(await page.locator('.quick-edit-drag-ghost').count(), 0, 'Swiping calendar space keeps native touch scrolling')
  } finally { await cdp.detach() }
}
async function swipeShelf(page) {
  const shelf = page.locator(".quick-edit-presets")
  const card = await shelf.locator(".quick-edit-preset").first().boundingBox()
  const cdp = await page.context().newCDPSession(page)
  const x = card.x + card.width - 12, y = card.y + card.height / 2
  await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x, y, id: 1 }] })
  for (let step = 1; step <= 12; step++) {
    await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: x - step * 10, y, id: 1 }] })
    if (step === 4) await page.waitForTimeout(250)
  }
  await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] })
  await page.waitForFunction(() => document.querySelector(".quick-edit-presets").scrollLeft > 20)
  assert.equal(await page.locator(".quick-edit-drag-ghost").count(), 0, "Swiping the shelf does not start dragging")
  await cdp.detach()
}

