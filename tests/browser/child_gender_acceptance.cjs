const assert = require('node:assert/strict')
const path = require('node:path')

async function exerciseChildGender({ browser, admin, origin, api, login, passwordSetup, passwords, axe, stage, out }) {
  stage('child gender: required onboarding/settings choices, placeholders, defaults, tag, avatar sync and persistence')
  const user = await api(admin, '/api/admin/users', 'POST', { loginName: 'qagender', nickname: '性别验收', password: passwords.initial })
  assert.equal(user.status, 200)
  const context = await browser.newContext({ viewport: { width: 1305, height: 890 } })
  const page = await context.newPage(); page.setDefaultTimeout(12000)
  try {
    await page.route('**/api/child-avatars', route => route.fulfill({ status: 503, json: { error: '头像暂不可用' } }))
    await login(page, 'qagender', passwords.initial)
    await passwordSetup(page, passwords.dad)
    await login(page, 'qagender', passwords.dad)
    await page.locator('#newChildName').fill('女孩验收')
    const form = page.locator('#createChildForm')
    await form.getByRole('button', { name: '创建孩子', exact: true }).click()
    assert.equal((await api(page, '/api/children')).children.length, 0)
    assert.equal(await form.locator('input[type="radio"]:checked').count(), 0)
    await form.getByRole('radio', { name: '女孩', exact: true }).check()
    assert.equal(await form.locator('[data-avatar-placeholder]').count(), 2)
    await axe(page, 'child-gender-onboarding-placeholder')
    await page.screenshot({ path: path.join(out, 'child-gender-onboarding-placeholder.png') })
    await form.getByRole('button', { name: '创建孩子', exact: true }).click()
    await page.locator('#calendarTitle').waitFor()
    const girl = (await api(page, '/api/children')).children[0]
    assert.equal(girl.gender, 'girl'); assert.equal(girl.avatarId, 'girl-10')
    await page.unroute('**/api/child-avatars'); await page.reload()
    await page.locator('[data-view="settings"]').click()
    await page.locator('[data-child-gender]').waitFor()
    const tag = page.locator('#changeChildGender'), dialog = page.locator('#childAvatarDialog')
    assert.equal(await tag.innerText(), '女孩')
    for (const [width, height] of [[1305, 890], [820, 1180], [390, 844]]) {
      await page.setViewportSize({ width, height })
      await tag.click()
      await dialog.getByRole('heading', { name: '修改头像和性别', exact: true }).waitFor()
      assert.equal(await dialog.getByRole('radio', { name: '女孩头像 10', exact: true }).isChecked(), true)
      await dialog.getByRole('radio', { name: '男孩头像 09', exact: true }).check()
      await axe(page, 'child-gender-avatar-' + width)
      await page.screenshot({ path: path.join(out, 'child-gender-avatar-' + width + '.png') })
      await dialog.getByRole('button', { name: '取消', exact: true }).click()
      await dialog.waitFor({ state: 'hidden' })
      assert.equal((await api(page, '/api/children')).children[0].gender, 'girl')
      await page.waitForFunction(() => document.activeElement?.id === 'changeChildGender')
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    }
    await page.setViewportSize({ width: 1305, height: 890 })
    await tag.click(); await dialog.getByRole('radio', { name: '男孩头像 09', exact: true }).check()
    await page.route(`**/api/children/${girl.id}`, route => route.fulfill({ status: 503, json: { error: '性别保存暂时失败' } }), { times: 1 })
    await page.locator('#saveChildAvatar').click()
    await dialog.getByText('性别保存暂时失败', { exact: true }).waitFor()
    assert.equal(await dialog.getByRole('radio', { name: '男孩头像 09', exact: true }).isChecked(), true)
    assert.equal((await api(page, '/api/children')).children[0].gender, 'girl')
    await page.locator('#saveChildAvatar').click(); await dialog.waitFor({ state: 'hidden' })
    assert.equal(await tag.innerText(), '男孩')
    await page.reload(); await page.locator('[data-view="settings"]').click()
    assert.equal(await page.locator('[data-child-gender]').innerText(), '男孩')
    const changed = (await api(page, '/api/children')).children[0]
    assert.equal(changed.gender, 'boy'); assert.equal(changed.avatarId, 'boy-09')
    await page.locator('#openCreateChild').click()
    const create = page.locator('#createChildDialog')
    await page.locator('#addChildName').fill('男孩验收')
    await create.getByRole('button', { name: '添加儿童', exact: true }).click()
    assert.equal((await api(page, '/api/children')).children.length, 1)
    await create.getByRole('radio', { name: '男孩', exact: true }).check()
    await axe(page, 'child-gender-settings-create')
    await page.screenshot({ path: path.join(out, 'child-gender-settings-create.png') })
    await create.getByRole('button', { name: '添加儿童', exact: true }).click()
    await create.waitFor({ state: 'hidden' }); await page.locator('#calendarTitle').waitFor()
    const boy = (await api(page, '/api/children')).children.find(c => c.name === '男孩验收')
    assert.equal(boy.gender, 'boy'); assert.equal(boy.avatarId, 'boy-04')
    await page.locator('[data-view="settings"]').click(); await page.locator('#changeChildAvatar').click()
    await dialog.getByRole('heading', { name: '修改头像和性别', exact: true }).waitFor()
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
    await page.waitForFunction(() => document.activeElement?.id === 'changeChildAvatar')
  } finally { await context.close() }
}
module.exports = { exerciseChildGender }
